def text_to_ascii(text):
    text = text.upper()
    lines = ["", "", "", "", ""]
    for char in text:
        pattern = ASCII_CHARS.get(char, ASCII_CHARS[' '])
        for i in range(5):
            lines[i] += pattern[i] + " "
    return "\n".join(lines)

def run(kevbin):
    kevbin.box.title("ASCII Art Generator")
    text = kevbin.box.input("Enter text: ")
    if not text:
        return
    result = text_to_ascii(text)
    kevbin.box.code(result)