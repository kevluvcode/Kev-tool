def _show_category(kevbin, cat_name, names):
    kevbin.clear()
    kevbin.section_header("📂", cat_name)
    kevbin.box_top()
    for i, name in enumerate(names[:50]):
        emoji = EMOJIS.get(name, "?")
        kevbin.box_row(f"{emoji}", name.replace('_', ' ').title())
    if len(names) > 50:
        kevbin.box_row("...", f"and {len(names) - 50} more")
    kevbin.box_bottom()
    kevbin.pause()

